# Copies content-data from LearningE_Server into the seed assets and records hashes in app/seed.lock.
# Usage: tools/sync-content.ps1 -Server D:\Android\LearningE_Server
# Files whose "source" starts with "Du lieu mau" (sample data) go to src/debug only, so they never reach a release.
param([Parameter(Mandatory = $true)][string]$Server)
$ErrorActionPreference = 'Stop'

$source = (Resolve-Path (Join-Path $Server 'content-data')).Path
$app = Join-Path (Split-Path $PSScriptRoot) 'app'
$repo = (git -C $Server config --get remote.origin.url).Trim() -replace '\.git$', ''
$commit = (git -C $Server log -1 --format=%H -- content-data).Trim()
if (git -C $Server status --porcelain -- content-data) { throw 'content-data has uncommitted changes' }
# This file stays ASCII: Windows PowerShell 5.1 reads scripts without BOM as ANSI.
$sample = [regex]::Unescape('^D\u1EEF li\u1EC7u m\u1EABu')

foreach ($set in 'main', 'debug') {
    $folder = Join-Path $app "src/$set/assets/seed"
    if (Test-Path $folder) { Remove-Item $folder -Recurse -Force }
}
$hashes = @()
$files = @('languages.json', 'exams.json')
$files += Get-ChildItem (Join-Path $source 'decks') -Filter *.json | ForEach-Object { "decks/$($_.Name)" }
foreach ($file in $files) {
    $text = [IO.File]::ReadAllText((Join-Path $source $file)) -replace "`r`n", "`n"
    $set = 'main'
    if ($file -ne 'languages.json') {
        $json = $text | ConvertFrom-Json
        if ($json.source -match $sample) { $set = 'debug' }
    }
    $target = Join-Path $app "src/$set/assets/seed/$file"
    New-Item -ItemType Directory -Force (Split-Path $target) | Out-Null
    [IO.File]::WriteAllText($target, $text)
    $hash = [Security.Cryptography.SHA256]::Create().ComputeHash([Text.Encoding]::UTF8.GetBytes($text))
    $hashes += "sha256 $set/$file " + (($hash | ForEach-Object { $_.ToString('x2') }) -join '')
}
$lines = @('# seed.lock - generated by tools/sync-content.ps1, do not edit by hand', "server_repo=$repo", "server_commit=$commit") + ($hashes | Sort-Object)
[IO.File]::WriteAllText((Join-Path $app 'seed.lock'), ($lines -join "`n") + "`n")
Write-Output "synced $($files.Count) files at $commit"
