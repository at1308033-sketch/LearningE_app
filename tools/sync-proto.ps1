# Copies the public proto package from LearningE_Server and records hashes in proto.lock (GRPC-API).
# Usage: tools/sync-proto.ps1 -Server D:\Android\LearningE_Server     copy and rewrite proto.lock
param([Parameter(Mandatory = $true)][string]$Server)
$ErrorActionPreference = 'Stop'

$source = Join-Path $Server 'proto/src/main/proto'
$target = Join-Path $PSScriptRoot '../app/src/main/proto'
$commit = (git -C $Server log -1 --format=%H -- proto/src/main/proto/learninge/app/v1).Trim()
$repo = (git -C $Server config --get remote.origin.url).Trim() -replace '\.git$', ''

$lines = @(
    '# proto.lock - generated by tools/sync-proto.ps1, do not edit by hand',
    "server_repo=$repo",
    "server_commit=$commit",
    "synced_at=$((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))"
)
$folder = Join-Path $target 'learninge/app/v1'
New-Item -ItemType Directory -Force $folder | Out-Null
Get-ChildItem (Join-Path $source 'learninge/app/v1') -Filter *.proto | Sort-Object Name | ForEach-Object {
    # Normalise line endings so the hash does not depend on git autocrlf.
    $text = [IO.File]::ReadAllText($_.FullName) -replace "`r`n", "`n"
    [IO.File]::WriteAllText((Join-Path $folder $_.Name), $text)
    $bytes = [Text.Encoding]::UTF8.GetBytes($text)
    $hash = [Security.Cryptography.SHA256]::Create().ComputeHash($bytes)
    $lines += "sha256 learninge/app/v1/$($_.Name) " + (($hash | ForEach-Object { $_.ToString('x2') }) -join '')
}
[IO.File]::WriteAllText((Join-Path $target 'proto.lock'), ($lines -join "`n") + "`n")
Write-Output "synced $($lines.Count - 4) files at $commit"
